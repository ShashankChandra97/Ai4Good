/**
 * Climate Action Lab — CSV Data Importer
 *
 * Reads `Data/baseline-sectors.csv` and compiles `Data/scenario-data.js`.
 * Run using:
 *   node Data/import-csv.js
 */

const fs = require('fs');
const path = require('path');

const csvPath = path.join(__dirname, 'baseline-sectors.csv');
const outJsPath = path.join(__dirname, 'scenario-data.js');

if (!fs.existsSync(csvPath)) {
  console.error(`Error: Could not find ${csvPath}`);
  process.exit(1);
}

const rawText = fs.readFileSync(csvPath, 'utf8').trim();

function parseCSV(text) {
  const lines = text.split(/\r?\n/).filter(line => line.trim().length > 0);
  if (lines.length < 2) {
    throw new Error('CSV must contain a header line and at least one data row.');
  }

  function splitLine(line) {
    const values = [];
    let current = '';
    let inQuotes = false;
    for (let i = 0; i < line.length; i++) {
      const char = line[i];
      if (char === '"') {
        if (inQuotes && line[i + 1] === '"') {
          current += '"';
          i++;
        } else {
          inQuotes = !inQuotes;
        }
      } else if (char === ',' && !inQuotes) {
        values.push(current.trim());
        current = '';
      } else {
        current += char;
      }
    }
    values.push(current.trim());
    return values;
  }

  const headers = splitLine(lines[0]).map(h => h.trim());
  const rows = [];

  for (let i = 1; i < lines.length; i++) {
    const cols = splitLine(lines[i]);
    const row = {};
    headers.forEach((h, idx) => {
      row[h] = cols[idx] !== undefined ? cols[idx] : '';
    });
    rows.push(row);
  }
  return rows;
}

try {
  const rows = parseCSV(rawText);
  const sectors = {};
  const requiredSectors = ['oil', 'electricity', 'transport'];

  rows.forEach(row => {
    const key = (row.sector || '').trim().toLowerCase();
    if (!key) return;

    const unit = row.unit ? row.unit.trim() : '';
    const baselineAnnualQuantity = parseFloat(row.baselineAnnualQuantity);
    const kgCO2PerUnit = parseFloat(row.kgCO2PerUnit);
    const costPerUnit = row.costPerUnit ? parseFloat(row.costPerUnit) : null;
    const description = row.description ? row.description.trim() : '';
    const source = row.source ? row.source.trim() : '';

    if (!unit) {
      throw new Error(`Sector '${key}' is missing a unit.`);
    }
    if (isNaN(baselineAnnualQuantity) || baselineAnnualQuantity < 0) {
      throw new Error(`Sector '${key}' has invalid baselineAnnualQuantity: ${row.baselineAnnualQuantity}`);
    }
    if (isNaN(kgCO2PerUnit) || kgCO2PerUnit < 0) {
      throw new Error(`Sector '${key}' has invalid kgCO2PerUnit: ${row.kgCO2PerUnit}`);
    }
    if (costPerUnit !== null && (isNaN(costPerUnit) || costPerUnit < 0)) {
      throw new Error(`Sector '${key}' has invalid costPerUnit: ${row.costPerUnit}`);
    }

    sectors[key] = {
      unit,
      baselineAnnualQuantity,
      kgCO2PerUnit,
      costPerUnit,
      ...(description ? { description } : {}),
      ...(source ? { source } : {})
    };
  });

  for (const req of requiredSectors) {
    if (!sectors[req]) {
      throw new Error(`Missing required sector '${req}' in CSV. Must include oil, electricity, and transport.`);
    }
  }

  // Load existing data if available to preserve areaName, currency, metadata
  let areaName = 'Metro Campus & Community Area';
  let currency = 'USD';
  let metadata = {
    dataSource: 'UNEP Emissions Gap Report 2026, EPA GHG Emission Factors Hub, UN SDG Indicator 13.2.2',
    updatedAt: new Date().toISOString().split('T')[0],
    geographicScope: 'Mid-sized institutional / municipal community campus',
    nonOverlappingCheck: 'Verified: Oil covers stationary heating only; transport covers vehicle mileage; electricity covers grid power.',
    disclaimer: 'Normalized index values are for educational scenario exploration and do not constitute official UN forecasts or measured real-time emissions.'
  };

  if (fs.existsSync(outJsPath)) {
    try {
      const existing = require(outJsPath);
      if (existing.areaName) areaName = existing.areaName;
      if (existing.currency) currency = existing.currency;
      if (existing.metadata) metadata = Object.assign(metadata, existing.metadata, { updatedAt: new Date().toISOString().split('T')[0] });
    } catch {
      // Ignore parse errors from existing file
    }
  }

  const climateData = {
    areaName,
    baselineYear: 2025,
    benchmark2030: 82,
    benchmark2035: 55,
    currency,
    sectors,
    metadata
  };

  const jsContent = `/* Climate Action Lab — Scenario Data Module
 * Generated by Data/import-csv.js from Data/baseline-sectors.csv
 * Assigns window.CLIMATE_DATA for the browser and Node environments.
 * Follows the data contract required by Engine/engine.js.
 */

(function (root) {
  'use strict';

  const climateData = ${JSON.stringify(climateData, null, 2)};

  root.CLIMATE_DATA = climateData;
  if (typeof module !== 'undefined' && module.exports) {
    module.exports = climateData;
  }
})(typeof window !== 'undefined' ? window : globalThis);
`;

  fs.writeFileSync(outJsPath, jsContent, 'utf8');
  console.log(`Successfully compiled ${csvPath} -> ${outJsPath}`);
  console.log(`Sectors imported: ${Object.keys(sectors).join(', ')}`);
} catch (err) {
  console.error(`Import failed: ${err.message}`);
  process.exit(1);
}
