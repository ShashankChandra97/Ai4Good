"""Extract a small, auditable browser dataset from Goal13.xlsx (stdlib only)."""

from __future__ import annotations

import hashlib
import json
import math
from pathlib import Path
import re
from xml.etree import ElementTree as ET
from zipfile import ZipFile


HERE = Path(__file__).resolve().parent
SOURCE = HERE / "Goal13.xlsx"
OUTPUT = HERE / "goal13-context.js"
NS = {"m": "http://schemas.openxmlformats.org/spreadsheetml/2006/main"}
SERIES = {
    "EN_ATM_GHGT_WOLU": ("emissions", "MT_CO2E"),
    "VC_DSR_DAFF": ("directlyAffected", "PER_100000_POP"),
    "VC_DSR_MTMP": ("deathsMissing", "PER_100000_POP"),
}


def cell_values(row, shared_strings):
    values = {}
    for cell in row.findall("m:c", NS):
        column = re.match(r"[A-Z]+", cell.attrib["r"]).group()
        raw = cell.find("m:v", NS)
        inline = cell.find("m:is", NS)
        value = raw.text if raw is not None else "".join(
            item.text or "" for item in inline.findall(".//m:t", NS)
        ) if inline is not None else ""
        if cell.attrib.get("t") == "s" and value:
            value = shared_strings[int(value)]
        values[column] = value
    return values


def extract():
    if not SOURCE.is_file():
        raise FileNotFoundError(SOURCE)
    shared = []
    countries = {}
    counts = {code: 0 for code in SERIES}
    with ZipFile(SOURCE) as book:
        if "xl/sharedStrings.xml" in book.namelist():
            strings = ET.fromstring(book.read("xl/sharedStrings.xml"))
            shared = ["".join(text.text or "" for text in item.findall(".//m:t", NS))
                      for item in strings.findall("m:si", NS)]
        sheet = ET.fromstring(book.read("xl/worksheets/sheet1.xml"))
        rows = sheet.findall("m:sheetData/m:row", NS)
        header = cell_values(rows[0], shared)
        expected = {"D": "SeriesCode", "F": "GeoAreaCode", "G": "GeoAreaName",
                    "H": "TimePeriod", "I": "Value", "R": "Nature", "S": "Units"}
        if any(header.get(column) != label for column, label in expected.items()):
            raise ValueError("Unexpected Goal13.xlsx column layout")
        for row in rows[1:]:
            values = cell_values(row, shared)
            code = values.get("D")
            if code not in SERIES or values.get("R") != "C":
                continue
            key, unit = SERIES[code]
            if values.get("S") != unit:
                raise ValueError(f"Unexpected unit for {code} at row {row.attrib['r']}")
            country_code = values.get("F")
            name = values.get("G")
            year = int(values["H"])
            value = float(values["I"])
            if not country_code or not name or not (1900 <= year <= 2100) or not math.isfinite(value) or value < 0:
                raise ValueError(f"Invalid {code} at row {row.attrib['r']}")
            country = countries.setdefault(country_code, {"code": country_code, "name": name,
                                                          "emissions": [], "directlyAffected": None,
                                                          "deathsMissing": None})
            if country["name"] != name:
                raise ValueError(f"Conflicting name for area {country_code}")
            if key == "emissions":
                if any(point["year"] == year for point in country[key]):
                    raise ValueError(f"Duplicate {code} for {name} in {year}")
                country[key].append({"year": year, "mtCO2e": value})
            else:
                current = country[key]
                if current is None or year > current["year"]:
                    country[key] = {"year": year, "per100k": value}
                elif year == current["year"]:
                    raise ValueError(f"Duplicate {code} for {name} in {year}")
            counts[code] += 1
    for country in countries.values():
        country["emissions"].sort(key=lambda point: point["year"])
    if counts != {"EN_ATM_GHGT_WOLU": 286, "VC_DSR_DAFF": 1955,
                  "VC_DSR_MTMP": 2122}:
        raise ValueError(f"Goal13.xlsx changed; review source before regeneration: {counts}")
    return {"source": "Data/Goal13.xlsx", "sha256": hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
            "indicators": {"emissions": "EN_ATM_GHGT_WOLU",
                           "directlyAffected": "VC_DSR_DAFF", "deathsMissing": "VC_DSR_MTMP"},
            "countries": sorted(countries.values(), key=lambda item: item["name"])}


if __name__ == "__main__":
    payload = json.dumps(extract(), ensure_ascii=False, separators=(",", ":"))
    OUTPUT.write_text(
        "/* Generated by Data/import-goal13.py from Data/Goal13.xlsx. Do not edit manually. */\n"
        "(function (root) {\n"
        f"  const context = {payload};\n"
        "  root.CLIMATE_GOAL13 = context;\n"
        "  if (typeof module !== 'undefined' && module.exports) module.exports = context;\n"
        "})(typeof window !== 'undefined' ? window : globalThis);\n",
        encoding="utf-8",
    )
    print(f"Wrote {OUTPUT}")
